from abc import ABC, abstractmethod
from datetime import datetime
from typing import Any
from .entities import Proposal

class ProposalRepository(ABC):
    @abstractmethod
    def upsert_many(self, proposals: list[Proposal]) -> int: ...
    @abstractmethod
    def list_all(self, limit: int = 10000) -> list[dict[str, Any]]: ...
    @abstractmethod
    def get(self, process_id: str) -> dict[str, Any] | None: ...
    @abstractmethod
    def count(self) -> int: ...
    @abstractmethod
    def save_snapshot(self, captured_at: datetime, total: int, active: int) -> None: ...
    @abstractmethod
    def list_snapshots(self, limit: int = 365) -> list[dict[str, Any]]: ...
    @abstractmethod
    def last_sync(self) -> datetime | None: ...
    @abstractmethod
    def mark_sync(self, at: datetime, status: str, message: str | None = None) -> None: ...

class SenadoGateway(ABC):
    @abstractmethod
    async def fetch_proposals(self) -> list[dict[str, Any]]: ...
    @abstractmethod
    async def fetch_process(self, process_id: str) -> dict[str, Any]: ...
    @abstractmethod
    async def fetch_senator_xml(self, code: str) -> str: ...
